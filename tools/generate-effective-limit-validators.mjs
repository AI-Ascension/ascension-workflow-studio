import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

// Compile in Node, never in the browser: Studio's script-src 'self' forbids
// runtime Function/eval. The generated validators retain the exact pinned
// closed JSON Schema semantics without weakening the application's CSP.
const ajv = new Ajv2020({ strict: false, code: { source: true, esm: true, lines: true } });
const schemas = {
  validateMemoryV3: 'context-memory-capabilities.schema.json',
  validateSessionV3: 'provider-session-capabilities.schema.json',
  validateSessionV1: 'provider-session-capabilities-v1.schema.json',
};
const ids = {};
for (const [name, file] of Object.entries(schemas)) {
  const schema = JSON.parse(readFileSync(new URL(`../contracts/accepted/effective-limits/${file}`, import.meta.url)));
  ajv.addSchema(schema);
  ids[name] = schema.$id;
}
let source = standaloneCode(ajv, ids);
// Ajv's ESM output still expresses runtime helper references as CJS require.
// Convert its fixed helper imports to static ESM for the browser bundler.
source = source.replace(/const (\w+) = require\("ajv\/dist\/runtime\/(\w+)"\)\.default;/g,
  'import $1Runtime from "ajv/dist/runtime/$2.js";\nconst $1 = typeof $1Runtime === "function" ? $1Runtime : $1Runtime.default;');
assert(!/\brequire\s*\(|\bnew Function\s*\(|\beval\s*\(/.test(source),
  'Generated capability validators must be static browser ESM');
source = '// Generated by tools/generate-effective-limit-validators.mjs from pinned schemas. Do not edit.\n' + source;
const target = fileURLToPath(new URL('../packages/contracts/src/effective-limit-validators.js', import.meta.url));
if (process.argv.includes('--check')) {
  assert.equal(readFileSync(target, 'utf8'), source, 'Effective-limit validators are stale; run the generator');
  // Native ESM and Vite's dev/production CJS interop differ. Exercise the actual
  // emitted module here as well as the browser suite, not only Vitest's loader.
  const validators = await import(pathToFileURL(target).href);
  const vectors = JSON.parse(readFileSync(new URL('../contracts/accepted/effective-limits/producer.json', import.meta.url)));
  for (const vector of vectors.memory) assert.equal(validators.validateMemoryV3(vector.descriptor), vector.producer_descriptor_valid);
  for (const vector of vectors.session) assert.equal(validators.validateSessionV3(vector.descriptor), vector.producer_descriptor_valid);
  console.log('Verified static effective-limit validators and original producer vectors in native ESM');
} else {
  writeFileSync(target, source);
}
